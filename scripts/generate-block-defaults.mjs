import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';

const reportPath = process.argv[2];
if (!reportPath) throw new Error('Usage: node scripts/generate-block-defaults.mjs <Mojang 1.21 generated/reports/blocks.json>');
const report = await readFile(resolve(reportPath));
const reportSha256 = createHash('sha256').update(report).digest('hex');
if (reportSha256 !== '0dde7f869588905763ea6ff2e7e01bec1db740a58d27477fd27c2f07fb029f73') {
  throw new Error('Expected the verified Mojang Java 1.21 blocks report; update provenance deliberately for a new source.');
}
const blocks = JSON.parse(report.toString('utf8'));
const states = {};
for (const [id, block] of Object.entries(blocks).sort(([a], [b]) => a.localeCompare(b, 'en'))) {
  const defaults = block.states.filter((state) => state.default);
  if (defaults.length !== 1) throw new Error(`${id}: expected exactly one default state.`);
  const properties = defaults[0].properties ?? {};
  if (Object.values(properties).some((value) => typeof value !== 'string')) throw new Error(`${id}: invalid default properties.`);
  if (Object.keys(properties).length) states[id] = properties;
}
// Lodestone also represents these entities as virtual blocks, outside Mojang's block registry.
states['minecraft:item_frame'] = { map: 'false' };
states['minecraft:glow_item_frame'] = { map: 'false' };
const entries = Object.entries(states).sort(([a], [b]) => a.localeCompare(b, 'en'));
const source = [
  '// Generated by scripts/generate-block-defaults.mjs from Mojang Java 1.21 reports.',
  '// Server SHA-1: 450698d1863ab5180c25d7c804ef0fe6369dd1ba',
  `// Report SHA-256: ${reportSha256}`,
  'export const vanillaBlockStates: Readonly<Record<string, Readonly<Record<string, string>>>> = {',
  ...entries.map(([id, properties]) => `  ${JSON.stringify(id)}: ${JSON.stringify(properties)},`),
  '};', '',
].join('\n');
await writeFile('frontend/src/integrations/vanillaBlockStates.ts', source);
console.log(JSON.stringify({ sourceBlocks: Object.keys(blocks).length, defaults: entries.length }));
