import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const { chromium } = require('../node_modules/.pnpm/playwright-core@1.63.0/node_modules/playwright-core');
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Users/l/AppData/Local/ms-playwright/chromium_headless_shell-1228/chrome-headless-shell-win64/chrome-headless-shell.exe', args: ['--use-gl=swiftshader'] });
const page = await browser.newPage();
const errors = [];
const failed = [];
page.on('pageerror', (error) => errors.push(error.message));
page.on('requestfailed', (request) => failed.push(`${request.url()}: ${request.failure()?.errorText}`));
await page.goto('http://127.0.0.1:4182/?ai-litematic-smoke=1');
await page.locator('#litematic-input').setInputFiles(fileURLToPath(new URL('../fixtures/ai-smoke.litematic', import.meta.url)));
await page.waitForFunction(() => document.querySelector('.canvas-hint')?.textContent?.includes('Litematic imported: 4 regions.'), null, { timeout: 10000 });
const info = await page.locator('#litematic-info').innerText();
assert.match(info, /gothic castle/);
assert.match(info, /main/);
assert.match(info, /roof/);
assert.match(info, /courtyard/);
assert.match(info, /tower/);
assert.match(info, /deepslate/);
const layers = await page.locator('#scene-layers').innerText();
assert.match(layers, /Litematic structure/);
await page.locator('#placement-input').setInputFiles({ name: 'placement.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ placements: [{ name: 'AI castle', pos: { x: 10, y: 64, z: -3 }, rotation: 'CLOCKWISE_90', mirror: 'NONE' }], selected: 0 })) });
await page.waitForFunction(() => document.querySelector('.canvas-hint')?.textContent?.includes('Placement loaded: 1 placement'), null, { timeout: 10000 });
assert.match(await page.locator('#litematic-placement').innerText(), /10, 64, -3/);
assert.deepEqual(errors, []);
assert.deepEqual(failed, []);
console.log(JSON.stringify({ info, layers, placement: await page.locator('#litematic-placement').innerText(), errors, failed }, null, 2));
await browser.close();

