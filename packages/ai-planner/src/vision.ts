import { createLitematicaPlannerInstruction, validateStructurePlan, type BuildingPrompt, type StructurePlan } from './index.js';

export type VisionPlannerOptions = {
  endpoint: string;
  apiKey?: string;
  model?: string;
  fetcher?: typeof fetch;
  maxRetries?: number;
  retryDelayMs?: number;
  maxRepairAttempts?: number;
  strictSchema?: boolean;
  requestTimeoutMs?: number;
};

const DEFAULT_RETRIES = 2;
const DEFAULT_REPAIR_ATTEMPTS = 1;
const DEFAULT_RETRY_DELAY_MS = 250;
const DEFAULT_REQUEST_TIMEOUT_MS = 30000;

export function structurePlanJsonSchema() {
  return {
    ...STRUCTURE_PLAN_SCHEMA,
    properties: {
      ...STRUCTURE_PLAN_SCHEMA.properties,
      inference: { type: 'object', additionalProperties: false, properties: { source: { type: 'string' }, detectedType: { type: 'string' }, detectedStyle: { type: 'string' }, confidence: { type: 'number' }, reasoning: { type: 'string' } } },
    },
  };
}

const STRUCTURE_PLAN_SCHEMA = { type: 'object', additionalProperties: false, required: ['version', 'name', 'type', 'style', 'dimensions', 'floors', 'rooms', 'regions', 'components', 'palette', 'seed', 'notes'], properties: { version: { type: 'integer', const: 1 }, name: { type: 'string' }, type: { type: 'string' }, style: { type: 'string' }, dimensions: { type: 'object', additionalProperties: false, required: ['width', 'height', 'length'], properties: { width: { type: 'integer', minimum: 1 }, height: { type: 'integer', minimum: 1 }, length: { type: 'integer', minimum: 1 } } }, floors: { type: 'integer', minimum: 1 }, rooms: { type: 'array', items: { type: 'object', additionalProperties: false, required: ['id', 'type', 'floor', 'x', 'y', 'z', 'width', 'height', 'length'], properties: { id: { type: 'string' }, type: { type: 'string' }, floor: { type: 'integer' }, x: { type: 'integer' }, y: { type: 'integer' }, z: { type: 'integer' }, width: { type: 'integer', minimum: 1 }, height: { type: 'integer', minimum: 1 }, length: { type: 'integer', minimum: 1 } } } }, regions: { type: 'array', minItems: 1, items: { type: 'object', additionalProperties: false, required: ['name', 'role', 'x', 'y', 'z', 'width', 'height', 'length'], properties: { name: { type: 'string' }, role: { type: 'string' }, x: { type: 'integer', minimum: 0 }, y: { type: 'integer', minimum: 0 }, z: { type: 'integer', minimum: 0 }, width: { type: 'integer', minimum: 1 }, height: { type: 'integer', minimum: 1 }, length: { type: 'integer', minimum: 1 } } } }, components: { type: 'array', items: { type: 'object', additionalProperties: false, required: ['id', 'type', 'x', 'y', 'z', 'options'], properties: { id: { type: 'string' }, type: { type: 'string' }, x: { type: 'integer' }, y: { type: 'integer' }, z: { type: 'integer' }, options: { type: 'object' } } } }, palette: { type: 'object', additionalProperties: { type: 'string' }, required: ['wall', 'floor', 'roof', 'window'] }, seed: { type: 'integer' }, notes: { type: 'array', items: { type: 'string' } } } } as const;

export async function planBuildingWithVision(input: BuildingPrompt, options: VisionPlannerOptions): Promise<StructurePlan> {
  if (!input.referenceImage?.dataUrl && !input.referenceImage?.url) throw new Error('Vision planning requires referenceImage.dataUrl or referenceImage.url.');
  return planBuildingWithModel(input, options);
}

export async function planBuildingWithModel(input: BuildingPrompt, options: VisionPlannerOptions): Promise<StructurePlan> {
  const imageUrl = input.referenceImage?.dataUrl ?? input.referenceImage?.url;
  if (!input.prompt?.trim() && !imageUrl) throw new Error('A building description or reference image is required.');
  if (!options.endpoint?.trim()) throw new Error('Vision planner endpoint is required.');

  const fetcher = options.fetcher ?? fetch;
  const headers: Record<string, string> = { 'content-type': 'application/json' };
  if (options.apiKey) headers.authorization = `Bearer ${options.apiKey}`;
  const request = buildRequest(input, imageUrl, options.model, options.strictSchema !== false);
  const response = await requestWithRetry(options.endpoint, headers, request, fetcher, options);
  const initial = parseVisionResponse(await response.text());

  try {
    validateStructurePlan(initial);
    return { ...initial, notes: [...initial.notes, 'Generated by a configured vision planner endpoint.'] };
  } catch (error) {
    const repaired = repairStructurePlan(initial);
    try {
      validateStructurePlan(repaired);
      return { ...repaired, notes: [...repaired.notes, `Auto-repaired vision response: ${error instanceof Error ? error.message : 'schema mismatch'}`] };
    } catch {
      if ((options.maxRepairAttempts ?? DEFAULT_REPAIR_ATTEMPTS) < 1) throw error;
      const repairRequest = buildRepairRequest(initial, error, options.model, options.strictSchema !== false);
      const repairedResponse = await requestWithRetry(options.endpoint, headers, repairRequest, fetcher, options);
      const repairedPlan = parseVisionResponse(await repairedResponse.text());
      validateStructurePlan(repairedPlan);
      return { ...repairedPlan, notes: [...repairedPlan.notes, 'Repaired by the configured vision planner endpoint.'] };
    }
  }
}

function buildRequest(input: BuildingPrompt, imageUrl?: string, model?: string, strictSchema = true) {
  const text = input.prompt?.trim() || 'Analyze this reference image and produce a buildable Minecraft structure plan.';
  return {
    model: model ?? 'gpt-4o-mini',
    temperature: 0,
    response_format: strictSchema ? { type: 'json_schema', json_schema: { name: 'structure_plan', strict: true, schema: structurePlanJsonSchema() } } : { type: 'json_object' },
    messages: [
      { role: 'system', content: createLitematicaPlannerInstruction() },
      { role: 'user', content: imageUrl ? [
        { type: 'text', text },
        { type: 'image_url', image_url: { url: imageUrl } },
      ] : text },
    ],
  };
}

function buildRepairRequest(plan: unknown, error: unknown, model?: string, strictSchema = true) {
  return {
    model: model ?? 'gpt-4o-mini',
    temperature: 0,
    response_format: strictSchema ? { type: 'json_schema', json_schema: { name: 'structure_plan', strict: true, schema: structurePlanJsonSchema() } } : { type: 'json_object' },
    messages: [
      { role: 'system', content: `${createLitematicaPlannerInstruction()} Repair the supplied JSON only. Return a complete valid StructurePlan JSON object. Do not add markdown.` },
      { role: 'user', content: `Invalid StructurePlan: ${JSON.stringify(plan)}\nValidation error: ${error instanceof Error ? error.message : 'schema mismatch'}` },
    ],
  };
}

async function requestWithRetry(endpoint: string, headers: Record<string, string>, body: unknown, fetcher: typeof fetch, options: VisionPlannerOptions): Promise<Response> {
  const maxRetries = Math.max(0, Math.min(5, Math.floor(options.maxRetries ?? DEFAULT_RETRIES)));
  const baseDelay = Math.max(0, Math.min(5000, Math.floor(options.retryDelayMs ?? DEFAULT_RETRY_DELAY_MS)));
  const timeoutMs = Math.max(1000, Math.min(120000, Math.floor(options.requestTimeoutMs ?? DEFAULT_REQUEST_TIMEOUT_MS)));
  let lastError: unknown;
  for (let attempt = 0; attempt <= maxRetries; attempt += 1) {
    try {
      const controller = new AbortController();
      const timeout = setTimeout(() => controller.abort(), timeoutMs);
      let response: Response;
      try {
        response = await fetcher(endpoint, { method: 'POST', headers, body: JSON.stringify(body), signal: controller.signal });
      } finally {
        clearTimeout(timeout);
      }
      if (response.ok || !isRetryableStatus(response.status) || attempt === maxRetries) {
        if (!response.ok) throw Object.assign(new Error(`Vision planner request failed (${response.status}).`), { statusCode: response.status, code: response.status === 429 ? 'RATE_LIMITED' : 'MODEL_REQUEST_FAILED' });
        return response;
      }
      lastError = new Error(`Vision planner request failed (${response.status}).`);
    } catch (error) {
      lastError = error instanceof DOMException && error.name === 'AbortError'
      ? Object.assign(new Error(`Vision planner request timed out after ${timeoutMs}ms.`), { statusCode: 504, code: 'MODEL_TIMEOUT' })
        : error;
      if (attempt === maxRetries) throw lastError;
    }
    await delay(baseDelay * 2 ** attempt);
  }
  throw lastError instanceof Error ? lastError : new Error('Vision planner request failed.');
}

function repairStructurePlan(value: any): StructurePlan {
  const dimensions = value?.dimensions ?? {};
  const width = positiveInt(dimensions.width, 16);
  const height = positiveInt(dimensions.height, 8);
  const length = positiveInt(dimensions.length, 16);
  const regions = Array.isArray(value?.regions) && value.regions.length ? value.regions : [{ name: 'main', role: 'main structure', x: 0, y: 0, z: 0, width, height, length }];
  const normalizedRegions = regions.map((region: any, index: number) => { const x = clampInt(region?.x, 0, width - 1); const y = clampInt(region?.y, 0, height - 1); const z = clampInt(region?.z, 0, length - 1); return { name: String(region?.name || `region-${index + 1}`), role: String(region?.role || 'structure'), x, y, z, width: clampInt(region?.width, 1, width - x), height: clampInt(region?.height, 1, height - y), length: clampInt(region?.length, 1, length - z) }; });
  return { version: 1, name: String(value?.name || 'Vision building'), type: String(value?.type || 'house'), style: String(value?.style || 'fantasy'), dimensions: { width, height, length }, floors: positiveInt(value?.floors, 1), rooms: Array.isArray(value?.rooms) ? value.rooms : [], regions: normalizedRegions, components: Array.isArray(value?.components) ? value.components : [], palette: { wall: value?.palette?.wall || 'minecraft:stone_bricks', floor: value?.palette?.floor || 'minecraft:oak_planks', roof: value?.palette?.roof || 'minecraft:dark_oak_planks', window: value?.palette?.window || 'minecraft:glass_pane' }, seed: Number.isFinite(Number(value?.seed)) ? Number(value.seed) : 42, notes: Array.isArray(value?.notes) ? value.notes : ['Response was locally repaired before validation.'] };
}

function parseVisionResponse(raw: string): StructurePlan {
  let envelope: any;
  try { envelope = JSON.parse(raw); } catch { throw new Error('Vision planner returned invalid JSON.'); }
  const content = envelope?.choices?.[0]?.message?.content ?? envelope?.output_text ?? envelope?.plan ?? envelope;
  const text = Array.isArray(content) ? content.map((part) => typeof part === 'string' ? part : part?.text ?? '').join('') : content;
  if (typeof text === 'object' && text) return text as StructurePlan;
  if (typeof text !== 'string') throw new Error('Vision planner response did not contain a StructurePlan.');
  const normalized = text.replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/, '').trim();
  try { return JSON.parse(normalized) as StructurePlan; } catch { throw new Error('Vision planner returned malformed StructurePlan JSON.'); }
}

function isRetryableStatus(status: number) { return status === 408 || status === 409 || status === 425 || status === 429 || status >= 500; }
function delay(ms: number) { return ms > 0 ? new Promise((resolve) => setTimeout(resolve, ms)) : Promise.resolve(); }
function positiveInt(value: unknown, fallback: number) { const number = Number(value); return Number.isInteger(number) && number > 0 ? number : fallback; }
function clampInt(value: unknown, min: number, max: number) { const number = Number(value); return Number.isInteger(number) ? Math.max(min, Math.min(max, number)) : min; }
